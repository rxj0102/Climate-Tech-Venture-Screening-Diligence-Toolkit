_STATUS_CHOICES: tuple[Status, ...] = ("resolved", "unresolved", "flagged")

# HIGH-severity items get diligenced first and hardest in a real process, so
# they are resolved more often than MEDIUM/LOW items -- otherwise nearly
# every deal would trip the override, which is not a realistic pipeline.
_STATUS_PROBABILITIES_BY_SEVERITY: dict[Severity, tuple[float, float, float]] = {
    "HIGH": (0.90, 0.06, 0.04),
    "MEDIUM": (0.65, 0.25, 0.10),
    "LOW": (0.75, 0.20, 0.05),
}

# The item used to surface Module 1's deliberately borderline deal's
# disqualifying flag during diligence.
_BORDERLINE_OVERRIDE_ITEM_ID = "team-02"


@dataclass(frozen=True)
class DiligenceItem:
    item_id: str
    category: Category
    description: str
    severity: Severity
    status: Status
    note: str | None = None


def deal_seed(seed: int, deal_id: str) -> int:
    """Deterministic per-deal integer seed derived from a global seed and
    the deal's id, so every module that needs deal-specific randomness
    (this one, and :mod:`diligence.deal_analysis`) can do so reproducibly
    without sharing mutable state."""
    digest = hashlib.sha256(f"{seed}:{deal_id}".encode()).hexdigest()
    return int(digest, 16) % (2**32)


def generate_diligence_status(deal: Deal, seed: int = 42) -> list[DiligenceItem]:
    """Synthetically assign a status to every checklist item for ``deal``.

    Deterministic given ``(deal.deal_id, seed)``. If the deal carries a
    disqualifying flag from Module 1, that flag is surfaced as a flagged,
    HIGH-severity diligence item so the recommendation engine has something
    concrete to react to.
    """
    rng = np.random.default_rng(deal_seed(seed, deal.deal_id))
    items = []
    for template in CHECKLIST_TEMPLATE:
        probabilities = _STATUS_PROBABILITIES_BY_SEVERITY[template.default_severity]
        status = str(rng.choice(_STATUS_CHOICES, p=probabilities))
        items.append(
            DiligenceItem(
                item_id=template.item_id,
                category=template.category,
                description=template.description,
                severity=template.default_severity,
                status=status,  # type: ignore[arg-type]
            )
        )

    if deal.disqualifying_flag is not None:
        items = [
            DiligenceItem(
                item_id=item.item_id,
                category=item.category,
                description=item.description,
                severity="HIGH",
                status="flagged",
                note=deal.disqualifying_flag,
            )
            if item.item_id == _BORDERLINE_OVERRIDE_ITEM_ID
            else item
            for item in items
        ]

    return items


def high_severity_unresolved(items: list[DiligenceItem]) -> list[DiligenceItem]:
    """HIGH-severity items that are not resolved (unresolved or flagged)."""
    return [i for i in items if i.severity == "HIGH" and i.status in ("unresolved", "flagged")]


def summarize_by_category(items: list[DiligenceItem]) -> dict[Category, dict[Status, int]]:
    summary: dict[Category, dict[Status, int]] = {}
    for item in items:
        category_summary = summary.setdefault(
            item.category, {"resolved": 0, "unresolved": 0, "flagged": 0}
        )
        category_summary[item.status] += 1
    return summary
