"""End-to-end entry point for the Climate Tech Venture Screening &
Diligence Toolkit.

Run with ``python main.py``. Runs all four modules in sequence against the
same seeded synthetic pipeline: screening & scoring (Module 1), the
standalone cost-curve/Monte Carlo demo (Module 2), the standalone
dilution/power-law demo (Module 3), and the diligence engine (Module 4) --
then generates a full investment committee memo for every shortlisted deal
and prints a final recommendation-count summary.

Every number in this script's output is derived from the synthetic,
seeded pipeline generated by :mod:`screening.data_generator`. Nothing here
is, or is intended to resemble, a real company or transaction.
"""

from __future__ import annotations

from collections import Counter

import diligence.main as diligence_main
import fund_returns.main as fund_returns_main
import screening.main as screening_main
import unit_economics.main as unit_economics_main
from diligence.checklist import generate_diligence_status
from diligence.deal_analysis import derive_fund_return_summary, derive_unit_economics_summary
from diligence.memo import generate_memo
from diligence.recommendation import recommend
from screening.data_generator import generate_pipeline
from screening.scoring import rank_pipeline, shortlist

SEED = 42
N_DEALS = 50
SHORTLIST_SIZE = 15


def _run_all_ic_memos() -> None:
    print("\n" + "=" * 88)
    print("FULL PIPELINE -- IC MEMOS FOR THE ENTIRE SHORTLIST")
    print("=" * 88)

    deals = generate_pipeline(n_deals=N_DEALS, seed=SEED)
    ranked = rank_pipeline(deals)
    top = shortlist(ranked, top_n=SHORTLIST_SIZE)

    decisions: Counter[str] = Counter()
    overrides = 0

    for result in top:
        items = generate_diligence_status(result.deal, seed=SEED)
        rec = recommend(result.composite_score, items)
        unit_econ = derive_unit_economics_summary(result.deal, seed=SEED)
        fund_return = derive_fund_return_summary(result.deal)
        memo = generate_memo(result, items, rec, unit_econ, fund_return)

        print(f"\n{'-' * 88}")
        print(memo)

        decisions[rec.decision] += 1
        if rec.overridden:
            overrides += 1

    print("=" * 88)
    print("RECOMMENDATION SUMMARY ACROSS SHORTLIST")
    print("=" * 88)
    for decision, count in sorted(decisions.items()):
        print(f"  {decision:<24} {count}")
    print(f"\n  Deals where a high score was overridden by diligence flags: {overrides}")


def run() -> None:
    print("#" * 88)
    print("# CLIMATE TECH VENTURE SCREENING & DILIGENCE TOOLKIT -- FULL END-TO-END RUN")
    print("# All data below is synthetic, seeded (seed=42), and generated by this repo.")
    print("#" * 88)

    screening_main.run(n_deals=N_DEALS, seed=SEED, shortlist_size=SHORTLIST_SIZE)
    unit_economics_main.run()
    fund_returns_main.run()
    diligence_main.run()
    _run_all_ic_memos()


if __name__ == "__main__":
    run()
